// Shared loader for spec/incident/deployments/*.json. Every consumer (firmware,
// backend) is generated from these files; nobody types a contract address by hand.
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

export const SPEC_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const REPO_ROOT = path.resolve(SPEC_DIR, '..', '..');
export const DEPLOYMENTS_DIR = path.join(SPEC_DIR, 'deployments');
export const ABI_FILE = path.join(REPO_ROOT, 'blockchain', 'abi', 'AirSafetyLog.json');

// ethers is already a dependency of server/api; reuse it instead of adding a package here.
const require = createRequire(path.join(REPO_ROOT, 'server', 'api', 'package.json'));
const { TypedDataEncoder, getAddress } = require('ethers');

export const KNOWN_NETWORKS = Object.freeze(['localhost', 'sepolia']);

function fail(file, message) {
    throw new Error(`${path.relative(REPO_ROOT, file)}: ${message}`);
}

// Loads and cross-checks one deployment: the recorded domainSeparator must equal the
// separator recomputed from name/version/chainId/address, so a hand-edited address
// cannot slip through generation.
export function loadDeployment(network) {
    const file = path.join(DEPLOYMENTS_DIR, `${network}.json`);
    if (!existsSync(file)) return null;
    const d = JSON.parse(readFileSync(file, 'utf8'));
    if (d.network !== network) fail(file, `network field is ${d.network}`);
    if (!/^[1-9][0-9]*$/.test(String(d.chainId))) fail(file, 'chainId must be a positive integer string');
    if (d.domain?.name !== 'AirSafetyLog' || d.domain?.version !== '1') fail(file, 'domain must be AirSafetyLog/1');
    const address = getAddress(d.address);
    const expected = TypedDataEncoder.hashDomain({
        name: d.domain.name,
        version: d.domain.version,
        chainId: BigInt(d.chainId),
        verifyingContract: address,
    });
    if (String(d.domainSeparator).toLowerCase() !== expected.toLowerCase()) {
        fail(file, `domainSeparator ${d.domainSeparator} does not match recomputed ${expected}`);
    }
    const legacy = (d.legacyAddresses ?? []).map((a) => getAddress(a));
    return Object.freeze({
        network,
        chainId: String(d.chainId),
        name: d.domain.name,
        version: d.domain.version,
        address,
        domainSeparator: expected,
        legacyAddresses: Object.freeze(legacy),
        deployTxHash: d.deployTxHash ?? null,
        blockNumber: Number(d.blockNumber ?? 0),
    });
}

export function loadAllDeployments() {
    const unknown = existsSync(DEPLOYMENTS_DIR)
        ? readdirSync(DEPLOYMENTS_DIR).filter((f) => f.endsWith('.json') && !KNOWN_NETWORKS.includes(f.slice(0, -5)))
        : [];
    if (unknown.length) throw new Error(`unknown deployment files in spec/incident/deployments: ${unknown.join(', ')}`);
    return Object.fromEntries(KNOWN_NETWORKS.map((n) => [n, loadDeployment(n)]).filter(([, d]) => d));
}

