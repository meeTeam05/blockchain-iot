// blockchain/deployments/<network>.incentives.json + blockchain/abi
//   -> server/api/src/generated/incentives-deployments.js
//
//   node spec/incident/gen/gen-incentives.mjs [--check]
// The incentives contracts only read AirSafetyLog, so each record must point at
// the AirSafetyLog of the same network in spec/incident/deployments.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { KNOWN_NETWORKS, REPO_ROOT, loadDeployment } from './common.mjs';

const require = createRequire(path.join(REPO_ROOT, 'server', 'api', 'package.json'));
const { getAddress } = require('ethers');

export const INCENTIVES_MODULE = path.join(REPO_ROOT, 'server/api/src/generated/incentives-deployments.js');
const DEPLOYMENTS_DIR = path.join(REPO_ROOT, 'blockchain', 'deployments');
const ABI_DIR = path.join(REPO_ROOT, 'blockchain', 'abi');
const BANNER = 'GENERATED by spec/incident/gen from blockchain/deployments/*.incentives.json. DO NOT EDIT.';

export function loadIncentivesDeployment(network) {
    const file = path.join(DEPLOYMENTS_DIR, `${network}.incentives.json`);
    if (!existsSync(file)) return null;
    const d = JSON.parse(readFileSync(file, 'utf8'));
    const where = path.relative(REPO_ROOT, file);
    if (d.network !== network) throw new Error(`${where}: network field is ${d.network}`);
    const log = loadDeployment(network);
    if (!log) throw new Error(`${where}: no spec/incident/deployments/${network}.json to pair with`);
    if (getAddress(d.airSafetyLog) !== log.address) {
        throw new Error(`${where}: airSafetyLog ${d.airSafetyLog} is not the ${network} AirSafetyLog ${log.address}`);
    }
    if (String(d.chainId) !== log.chainId) throw new Error(`${where}: chainId ${d.chainId} != ${log.chainId}`);
    return {
        network,
        chainId: log.chainId,
        airSafetyLog: log.address,
        token: { address: getAddress(d.token.address), blockNumber: Number(d.token.blockNumber) },
        incentives: {
            address: getAddress(d.incentives.address),
            blockNumber: Number(d.incentives.blockNumber),
            activatedAt: String(d.incentives.activatedAt),
        },
        treasury: getAddress(d.treasury),
        operator: getAddress(d.operator),
    };
}

export function renderIncentivesModule() {
    const deployments = Object.fromEntries(
        KNOWN_NETWORKS.map((n) => [n, loadIncentivesDeployment(n)]).filter(([, d]) => d),
    );
    const abi = (name) => JSON.parse(readFileSync(path.join(ABI_DIR, `${name}.json`), 'utf8'));
    return `// ${BANNER}
// Regenerate with: node spec/incident/gen/gen-all.mjs

export const INCENTIVES_DEPLOYMENTS = Object.freeze(${JSON.stringify(deployments, null, 4)});

export const SAFETY_INCENTIVES_ABI = Object.freeze(${JSON.stringify(abi('SafetyIncentives'))});

export const AIR_SAFE_TOKEN_ABI = Object.freeze(${JSON.stringify(abi('AirSafeToken'))});
`;
}

export function generateIncentives({ check = false } = {}) {
    const next = renderIncentivesModule();
    const current = existsSync(INCENTIVES_MODULE) ? readFileSync(INCENTIVES_MODULE, 'utf8').replace(/\r\n/g, '\n') : null;
    if (check) return current === next;
    mkdirSync(path.dirname(INCENTIVES_MODULE), { recursive: true });
    if (current !== next) writeFileSync(INCENTIVES_MODULE, next);
    return true;
}

if (process.argv[1]?.endsWith('gen-incentives.mjs')) {
    const check = process.argv.includes('--check');
    const ok = generateIncentives({ check });
    if (check && !ok) {
        console.error('incentives-deployments.js is stale: run node spec/incident/gen/gen-all.mjs');
        process.exit(1);
    }
    console.log(check ? 'incentives-deployments.js up to date' : `wrote ${path.relative(REPO_ROOT, INCENTIVES_MODULE)}`);
}
